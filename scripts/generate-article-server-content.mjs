import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ARTICLE_DOCUMENT_CLASS = "dq-article-document";
const articles = [
  ["deutsche-sprache-geschichte", "deutsche-sprache-geschichte.html"],
  ["pruefungen-goethe-telc-testdaf", "pruefungen-goethe-telc-testdaf.html"],
  ["sprachniveaus-a0-c2", "sprachniveaus-a0-c2.html"],
];

const ROOT_BODY_SELECTOR_PATTERN = /(^|[,{])(\s*)body(?=\s*(?:[,{>+~.#:\[]|$))/gm;

function scopeRootSelectors(styles) {
  const scopedDocumentSelector = `.${ARTICLE_DOCUMENT_CLASS}`;

  return styles
    .replace(/:root/g, scopedDocumentSelector)
    .replace(
      ROOT_BODY_SELECTOR_PATTERN,
      (_match, boundary, whitespace) =>
        `${boundary}${whitespace}${scopedDocumentSelector}`,
    );
}

function extractArticleBodyAndStyles(html) {
  const normalizedHtml = html.replace(/\r\n?/g, "\n");
  const styleTags = normalizedHtml.match(/<style[^>]*>([\s\S]*?)<\/style>/gi) ?? [];
  const styles = styleTags
    .map((styleTag) => {
      const extractedStyles = styleTag
        .replace(/^<style[^>]*>/i, "")
        .replace(/<\/style>$/i, "");

      return scopeRootSelectors(extractedStyles);
    })
    .join("\n\n");

  let content = normalizedHtml.replace(/<style[^>]*>[\s\S]*?<\/style>/gi, "");
  const bodyMatch = content.match(/<body[^>]*>([\s\S]*?)<\/body>/i);

  if (bodyMatch) {
    content = bodyMatch[1];
  }

  return { content, styles };
}

const payload = Object.fromEntries(
  articles.map(([slug, fileName]) => {
    const source = readFileSync(
      join(process.cwd(), "content", "artikel", fileName),
      "utf8",
    );

    return [slug, extractArticleBodyAndStyles(source)];
  }),
);

const output = `// Generated by scripts/generate-article-server-content.mjs.\n` +
  `export type ArticleServerPayload = {\n  content: string;\n  styles: string;\n};\n\n` +
  `export const ARTICLE_SERVER_RENDERED_PAYLOAD: Record<string, ArticleServerPayload> = ${JSON.stringify(payload, null, 2)};\n`;

writeFileSync(
  join(process.cwd(), "lib", "article-server-rendered-content.ts"),
  output,
  "utf8",
);
